#!/usr/bin/env bash
# Builds the single-file collectors in dist/ from lib/common.sh + src/*.body.sh.
set -e
cd "$(dirname "$0")"; mkdir -p dist
for body in src/*.body.sh; do
  name=$(basename "$body" .body.sh)
  { echo '#!/usr/bin/env bash'
    echo "# $name.sh — generated by collectors/build.sh; edit src/ and lib/ instead."
    echo '# Read-only homelab collector. Produces a timestamped, redacted .tar.gz to send back.'
    cat lib/common.sh; echo; cat "$body"; } > "dist/$name.sh"
  chmod +x "dist/$name.sh"; bash -n "dist/$name.sh"
done
ls -1 dist
